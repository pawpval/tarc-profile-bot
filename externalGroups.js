function normalizeExternal(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[’']/g, "'")
    .replace(/[^a-z0-9_\-\s']/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function tokenize(text) {
  return new Set(
    normalizeExternal(text)
      .split(" ")
      .filter((token) => token.length >= 2)
  );
}

function groupSearchText(group) {
  return normalizeExternal([
    group.name,
    ...(group.aliases || []),
    group.groupId || "",
    group.statusScale || "",
    group.known || "",
    group.notes || ""
  ].join(" "));
}

export function findRelevantExternalGroups(question, limit = 4) {
  const q = normalizeExternal(question);
  if (!q) return [];

  const qTokens = tokenize(q);

  const scored = EXTERNAL_STAR_WARS_GROUPS.map((group) => {
    const search = groupSearchText(group);
    let score = 0;

    for (const alias of group.aliases || []) {
      const a = normalizeExternal(alias);
      if (!a) continue;
      if (q === a) score += 80;
      else if (q.includes(a)) score += a.length <= 4 ? 45 : 65;
    }

    if (group.groupId && q.includes(String(group.groupId))) score += 90;

    const name = normalizeExternal(group.name);
    if (name && q.includes(name)) score += 70;

    for (const token of qTokens) {
      if (token.length >= 3 && search.includes(token)) score += 2;
    }

    return { group, score };
  })
    .filter((item) => item.score >= 8)
    .sort((a, b) => b.score - a.score)
    .slice(0, Math.max(1, Math.min(8, Number(limit) || 4)));

  return scored.map((item) => item.group);
}

